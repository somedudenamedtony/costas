using System.Net;
using System.Net.Sockets;

namespace Ft8Client.Core.Remote;

/// <summary>Which addresses count as this home network: the remote page refuses everything else.</summary>
public static class LocalNetwork
{
    /// <summary>
    /// True for loopback, private IPv4 (10/8, 172.16/12, 192.168/16), link-local, carrier-grade NAT (100.64/10, used by
    /// Tailscale), and IPv6 unique-local and link-local addresses.
    /// </summary>
    public static bool Contains(IPAddress? address)
    {
        if (address is null) return false;
        if (address.IsIPv4MappedToIPv6) address = address.MapToIPv4();
        if (IPAddress.IsLoopback(address)) return true;
        if (address.AddressFamily == AddressFamily.InterNetwork)
        {
            var b = address.GetAddressBytes();
            return b[0] == 10
                || (b[0] == 172 && b[1] >= 16 && b[1] <= 31)
                || (b[0] == 192 && b[1] == 168)
                || (b[0] == 169 && b[1] == 254)
                || (b[0] == 100 && b[1] >= 64 && b[1] <= 127);
        }
        if (address.AddressFamily == AddressFamily.InterNetworkV6)
        {
            var b = address.GetAddressBytes();
            return address.IsIPv6LinkLocal || (b[0] & 0xFE) == 0xFC;
        }
        return false;
    }
}
